-- Fondasi database dan keamanan panel admin Zonasi UMKM.
-- Jalankan melalui Supabase SQL Editor atau Supabase CLI.

create extension if not exists pgcrypto;

create table if not exists public.admin_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default 'Administrator',
  role text not null default 'admin'
    check (role in ('superadmin', 'admin', 'verifikator', 'viewer')),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.umkm (
  id bigint generated by default as identity primary key
    constraint umkm_id_nonnegative check (id >= 0),
  name text not null,
  product_type text not null default '',
  product_label text not null default '',
  brand text not null default '',
  owner text not null default '',
  address text not null default '',
  lat double precision,
  lng double precision,
  analysis_lat double precision,
  analysis_lng double precision,
  display_lat double precision,
  display_lng double precision,
  location_accuracy text not null default 'belum_terverifikasi'
    check (location_accuracy in ('tepat', 'perkiraan_kecamatan', 'belum_terverifikasi')),
  location_area text not null default '',
  is_active boolean not null default true,
  published boolean not null default true,
  verified_at timestamptz,
  -- Exact-location history must retain a valid verifier. Deleting an Auth user
  -- is therefore blocked until their verified rows are reassigned/downgraded.
  verified_by uuid references auth.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint umkm_legacy_coordinates_pair
    check ((lat is null) = (lng is null)),
  constraint umkm_analysis_coordinates_pair
    check ((analysis_lat is null) = (analysis_lng is null)),
  constraint umkm_display_coordinates_pair
    check ((display_lat is null) = (display_lng is null)),
  constraint umkm_legacy_latitude_range
    check (lat is null or lat between -90 and 90),
  constraint umkm_legacy_longitude_range
    check (lng is null or lng between -180 and 180),
  constraint umkm_analysis_latitude_range
    check (analysis_lat is null or analysis_lat between -90 and 90),
  constraint umkm_analysis_longitude_range
    check (analysis_lng is null or analysis_lng between -180 and 180),
  constraint umkm_display_latitude_range
    check (display_lat is null or display_lat between -90 and 90),
  constraint umkm_display_longitude_range
    check (display_lng is null or display_lng between -180 and 180),
  constraint umkm_exact_location_metadata
    check (
      location_accuracy <> 'tepat'
      or (
        analysis_lat is not null
        and analysis_lng is not null
        and display_lat is not null
        and display_lng is not null
        and lat is not null
        and lng is not null
        and verified_at is not null
        and verified_by is not null
      )
    )
);

create table if not exists public.kmeans_runs (
  id uuid primary key default gen_random_uuid(),
  k_value integer not null check (k_value between 2 and 20),
  data_count integer not null check (data_count >= 0),
  iterations integer not null check (iterations >= 0),
  wcss double precision not null check (wcss >= 0),
  centroids jsonb not null default '[]'::jsonb,
  cluster_stats jsonb not null default '[]'::jsonb,
  parameters jsonb not null default '{}'::jsonb,
  dataset_hash text not null,
  input_snapshot jsonb not null default '[]'::jsonb,
  created_by uuid references auth.users(id) on delete set null default auth.uid(),
  created_at timestamptz not null default now(),
  constraint kmeans_runs_dataset_hash_required
    check (dataset_hash is not null and btrim(dataset_hash) <> ''),
  constraint kmeans_runs_snapshot_matches_count
    check (
      jsonb_typeof(input_snapshot) = 'array'
      and jsonb_array_length(input_snapshot) = data_count
    )
);

create table if not exists public.import_batches (
  id uuid primary key default gen_random_uuid(),
