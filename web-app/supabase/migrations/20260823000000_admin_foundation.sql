create or replace function public.verify_umkm_location(
  p_umkm_id bigint,
  p_lat double precision,
  p_lng double precision,
  p_location_accuracy text,
  p_location_area text default ''
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  verified_business public.umkm%rowtype;
  previous_verification_context text;
  business_was_found boolean := false;
begin
  if not public.can_verify_umkm() then
    raise exception 'Akun tidak memiliki izin untuk memverifikasi lokasi.'
      using errcode = '42501';
  end if;

  if p_lat is null or p_lat < -90 or p_lat > 90 then
    raise exception 'Latitude harus berada pada rentang -90 sampai 90.'
      using errcode = '22023';
  end if;

  if p_lng is null or p_lng < -180 or p_lng > 180 then
    raise exception 'Longitude harus berada pada rentang -180 sampai 180.'
      using errcode = '22023';
  end if;

  if p_location_accuracy not in ('tepat', 'perkiraan_kecamatan') then
    raise exception 'Status verifikasi lokasi tidak valid.'
      using errcode = '22023';
  end if;

  previous_verification_context :=
    current_setting('app.verify_umkm_location', true);
  perform set_config('app.verify_umkm_location', 'on', true);

  begin
    update public.umkm
    set analysis_lat = p_lat,
        analysis_lng = p_lng,
        display_lat = p_lat,
        display_lng = p_lng,
        lat = p_lat,
        lng = p_lng,
        location_accuracy = p_location_accuracy,
        location_area = coalesce(p_location_area, '')
    where id = p_umkm_id
    returning * into verified_business;

    business_was_found := found;
  exception
    when others then
      perform set_config(
        'app.verify_umkm_location',
        coalesce(nullif(previous_verification_context, ''), 'off'),
        true
      );
      raise;
  end;

  perform set_config(
    'app.verify_umkm_location',
    coalesce(nullif(previous_verification_context, ''), 'off'),
    true
  );

  if not business_was_found then
    raise exception 'Data UMKM dengan ID % tidak ditemukan.', p_umkm_id
      using errcode = 'P0002';
  end if;

  return to_jsonb(verified_business);
end;
$$;

