create or replace function public.import_umkm_batch(
  p_source_name text,
  p_records jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  batch public.import_batches%rowtype;
  item jsonb;
  total_count integer := case
    when jsonb_typeof(p_records) = 'array' then jsonb_array_length(p_records)
    else 0
  end;
  current_row integer := 0;
  imported_id bigint;
  imported_name text;
  imported_product_type text;
  imported_product_label text;
  imported_brand text;
  imported_owner text;
  imported_address text;
  imported_analysis_lat double precision;
  imported_analysis_lng double precision;
  imported_display_lat double precision;
  imported_display_lng double precision;
  imported_accuracy text;
  imported_area text;
  imported_is_active boolean;
  imported_published boolean;
begin
  if not public.can_manage_umkm() then
    raise exception 'Akun tidak memiliki izin untuk mengimpor data UMKM.'
      using errcode = '42501';
  end if;

  insert into public.import_batches (
    source_name,
    total_rows,
    valid_rows,
    invalid_rows,
    status,
    error_message,
    imported_by
  ) values (
    coalesce(nullif(btrim(p_source_name), ''), 'Impor tanpa nama'),
    total_count,
    0,
    0,
    'processing',
    null,
    auth.uid()
  ) returning * into batch;

  -- A PL/pgSQL block with EXCEPTION is a subtransaction. If any row fails,
  -- every UMKM mutation below is rolled back, while the batch row created
  -- above remains available to be marked as failed.
  begin
    if p_records is null or jsonb_typeof(p_records) <> 'array' then
      raise exception 'Payload records harus berupa array JSON.'
        using errcode = '22023';
    end if;

    -- Serialize imports and direct writes while explicit legacy IDs are being
    -- loaded and the identity sequence is synchronized.
    lock table public.umkm in share row exclusive mode;

    for item in
      select value from jsonb_array_elements(p_records)
    loop
      current_row := current_row + 1;

      if jsonb_typeof(item) <> 'object' then
        raise exception 'Baris % bukan objek JSON.', current_row
          using errcode = '22023';
      end if;

      imported_id := nullif(item ->> 'id', '')::bigint;
      imported_name := coalesce(
        nullif(btrim(item ->> 'name'), ''),
        'Data UMKM'
      );
      imported_product_type := coalesce(btrim(item ->> 'product_type'), '');
      imported_product_label := coalesce(btrim(item ->> 'product_label'), '');
      imported_brand := coalesce(btrim(item ->> 'brand'), '');
      imported_owner := coalesce(btrim(item ->> 'owner'), '');
      imported_address := coalesce(btrim(item ->> 'address'), '');
      imported_analysis_lat := coalesce(
        nullif(item ->> 'analysis_lat', '')::double precision,
        nullif(item ->> 'lat', '')::double precision
      );
      imported_analysis_lng := coalesce(
        nullif(item ->> 'analysis_lng', '')::double precision,
        nullif(item ->> 'lng', '')::double precision
      );
      imported_display_lat := coalesce(
        nullif(item ->> 'display_lat', '')::double precision,
        nullif(item ->> 'lat', '')::double precision,
        imported_analysis_lat
      );
      imported_display_lng := coalesce(
        nullif(item ->> 'display_lng', '')::double precision,
        nullif(item ->> 'lng', '')::double precision,
        imported_analysis_lng
      );
      imported_accuracy := coalesce(
        nullif(btrim(item ->> 'location_accuracy'), ''),
        'belum_terverifikasi'
      );
      if imported_accuracy = 'tepat' then
        raise exception
          'Status lokasi tepat tidak boleh diimpor; tetapkan melalui fitur verifikasi lokasi.'
          using errcode = '42501';
      end if;
      imported_area := coalesce(btrim(item ->> 'location_area'), '');
      imported_is_active := coalesce(
        nullif(item ->> 'is_active', '')::boolean,
        true
      );
      imported_published := coalesce(
        nullif(item ->> 'published', '')::boolean,
        true
      );

      if imported_id is null then
        insert into public.umkm (
          name, product_type, product_label, brand, owner, address,
          lat, lng, analysis_lat, analysis_lng, display_lat, display_lng,
          location_accuracy, location_area, is_active, published
        ) values (
          imported_name, imported_product_type, imported_product_label,
          imported_brand, imported_owner, imported_address,
          imported_display_lat, imported_display_lng,
          imported_analysis_lat, imported_analysis_lng,
          imported_display_lat, imported_display_lng,
          imported_accuracy, imported_area,
          imported_is_active, imported_published
        );
      else
        insert into public.umkm (
          id, name, product_type, product_label, brand, owner, address,
          lat, lng, analysis_lat, analysis_lng, display_lat, display_lng,
          location_accuracy, location_area, is_active, published
        ) values (
          imported_id, imported_name, imported_product_type,
          imported_product_label, imported_brand, imported_owner,
          imported_address, imported_display_lat, imported_display_lng,
          imported_analysis_lat, imported_analysis_lng,
          imported_display_lat, imported_display_lng,
          imported_accuracy, imported_area,
          imported_is_active, imported_published
        )
        on conflict (id) do update
        set name = excluded.name,
            product_type = excluded.product_type,
            product_label = excluded.product_label,
            brand = excluded.brand,
            owner = excluded.owner,
            address = excluded.address,
            lat = excluded.lat,
            lng = excluded.lng,
            analysis_lat = excluded.analysis_lat,
            analysis_lng = excluded.analysis_lng,
            display_lat = excluded.display_lat,
            display_lng = excluded.display_lng,
            location_accuracy = excluded.location_accuracy,
            location_area = excluded.location_area,
            is_active = excluded.is_active,
            published = excluded.published;
      end if;
    end loop;

    -- Explicit IDs do not advance a PostgreSQL identity sequence. Set it to
    -- the first unused value so the next regular insert cannot collide.
    perform setval(
      pg_get_serial_sequence('public.umkm', 'id'),
      greatest(
        coalesce((select max(id) from public.umkm), 0) + 1,
        (
          select last_value + case when is_called then 1 else 0 end
          from public.umkm_id_seq
        ),
        1
      ),
      false
    );
  exception
    when others then
      update public.import_batches
      set status = 'failed',
          valid_rows = 0,
          invalid_rows = total_count,
          error_message = left(
            format('Baris %s: %s', greatest(current_row, 1), sqlerrm),
            4000
          )
      where id = batch.id
      returning * into batch;

      return jsonb_build_object(
        'success', false,
        'message', batch.error_message,
        'batch_id', batch.id,
        'status', batch.status,
        'total_rows', batch.total_rows,
        'valid_rows', batch.valid_rows,
        'invalid_rows', batch.invalid_rows
      );
  end;

  update public.import_batches
  set status = 'completed',
      valid_rows = total_count,
      invalid_rows = 0,
      error_message = null
  where id = batch.id
  returning * into batch;

  return jsonb_build_object(
    'success', true,
    'message', format('%s data berhasil diimpor.', total_count),
    'batch_id', batch.id,
    'status', batch.status,
    'total_rows', batch.total_rows,
    'valid_rows', batch.valid_rows,
    'invalid_rows', batch.invalid_rows
  );
end;
$$;

