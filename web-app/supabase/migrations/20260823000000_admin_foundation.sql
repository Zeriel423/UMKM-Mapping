create or replace function public.normalize_umkm_location()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  verification_flow boolean :=
    coalesce(current_setting('app.verify_umkm_location', true), 'off') = 'on';
begin
  -- A manager may still edit ordinary business metadata on an exact record,
  -- but exact status/location/verification metadata can only be touched by the
  -- guarded verify_umkm_location() RPC below.
  if tg_op = 'INSERT' then
    if new.location_accuracy = 'tepat' and not verification_flow then
      raise exception
        'Status lokasi tepat hanya dapat ditetapkan melalui verifikasi lokasi.'
        using errcode = '42501';
    end if;
  elsif not verification_flow
    and (old.location_accuracy = 'tepat' or new.location_accuracy = 'tepat')
    and (
      old.location_accuracy is distinct from new.location_accuracy
      or old.analysis_lat is distinct from new.analysis_lat
      or old.analysis_lng is distinct from new.analysis_lng
      or old.display_lat is distinct from new.display_lat
      or old.display_lng is distinct from new.display_lng
      or old.lat is distinct from new.lat
      or old.lng is distinct from new.lng
      or old.location_area is distinct from new.location_area
      or old.verified_at is distinct from new.verified_at
      or old.verified_by is distinct from new.verified_by
    ) then
    raise exception
      'Status, koordinat, wilayah, dan metadata lokasi tepat hanya dapat diubah melalui verifikasi lokasi.'
      using errcode = '42501';
  end if;

  if new.location_accuracy = 'tepat' then
    if verification_flow then
      -- Exact locations use one canonical coordinate for analysis, display,
      -- and legacy clients. The table constraint rejects an incomplete pair.
      new.display_lat := new.analysis_lat;
      new.display_lng := new.analysis_lng;
      new.lat := new.analysis_lat;
      new.lng := new.analysis_lng;
      new.verified_at := now();
      new.verified_by := coalesce(auth.uid(), new.verified_by);
    elsif tg_op = 'UPDATE' then
      -- Preserve the original verification evidence during ordinary edits to
      -- fields such as name, category, owner, publication, or active status.
      new.location_accuracy := old.location_accuracy;
      new.analysis_lat := old.analysis_lat;
      new.analysis_lng := old.analysis_lng;
      new.display_lat := old.display_lat;
      new.display_lng := old.display_lng;
      new.lat := old.lat;
      new.lng := old.lng;
      new.location_area := old.location_area;
      new.verified_at := old.verified_at;
      new.verified_by := old.verified_by;
    end if;
  else
    -- Verification metadata must never survive after a location is downgraded.
    new.verified_at := null;
    new.verified_by := null;
  end if;

  return new;
end;
$$;

create or replace function public.audit_umkm_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  affected_id text;
begin
  affected_id := coalesce(new.id, old.id)::text;
  insert into public.audit_logs (
    table_name, record_id, action, old_data, new_data, actor_id, actor_email
  ) values (
    tg_table_name,
    affected_id,
    tg_op,
    case when tg_op in ('UPDATE', 'DELETE') then to_jsonb(old) else null end,
    case when tg_op in ('INSERT', 'UPDATE') then to_jsonb(new) else null end,
    (select auth.uid()),
    (select auth.jwt() ->> 'email')
  );
  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

